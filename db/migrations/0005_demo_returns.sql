-- A second fact table for the demo (ADR 0014): returned order items, refunded whole, at most
-- once each. Deleting an order (the tick's 90-day window) deletes its items and their returns.
create table dash_demo.returns (
  id bigint generated by default as identity primary key,
  tenant_id int not null references dash_demo.tenants (id),
  order_item_id bigint not null unique references dash_demo.order_items (id) on delete cascade,
  quantity int not null,
  refunded_amount numeric(10, 2) not null,
  returned_at timestamptz not null
);

-- The same read access and tenant policy as the other demo tables (0000_init).
grant select on dash_demo.returns to dash_reader;
alter table dash_demo.returns enable row level security;
create policy tenant_scope on dash_demo.returns for select to dash_reader
  using (tenant_id = any((select string_to_array(current_setting('app.tenant_ids', true), ',')::int[])::int[]));

-- About one item in twenty of the existing data comes back, picked by a hash of its id, one to
-- fourteen days after its order (seed.sql does the same for a new database).
insert into dash_demo.returns (tenant_id, order_item_id, quantity, refunded_amount, returned_at)
select i.tenant_id, i.id, i.quantity, i.quantity * i.unit_price,
  least(now(), o.ordered_at + (1 + i.id % 14) * interval '1 day')
from dash_demo.order_items i
join dash_demo.orders o on o.id = i.order_id
where hashint8(i.id) % 20 = 0
on conflict do nothing;

-- The tick as in 0001, plus a return on every tenth order: a recent item of the same tenant
-- that hasn't come back yet. `create or replace` resets the settings, so the path is set again.
create or replace function dash_demo.tick() returns void
language plpgsql
set search_path = ''
as $$
declare
  t int;
  new_order bigint;
begin
  delete from dash_demo.orders where ordered_at < now() - interval '90 days';
  -- pg_cron logs every run and never purges; keep a day of this job's history only.
  delete from cron.job_run_details
  where jobid in (select jobid from cron.job where jobname = 'dash_demo_tick')
    and end_time < now() - interval '1 day';

  select id into t from dash_demo.tenants order by random() limit 1;

  insert into dash_demo.orders (tenant_id, customer_id, ordered_at, status, channel)
  select t, c.id, now(),
    (array['paid', 'paid', 'paid', 'shipped', 'refunded'])[1 + floor(random() * 5)::int],
    (array['web', 'mobile', 'store'])[1 + floor(random() * 3)::int]
  from dash_demo.customers c
  where c.tenant_id = t
  order by random()
  limit 1
  returning id into new_order;

  if new_order is null then
    return;
  end if;

  insert into dash_demo.order_items (order_id, tenant_id, product_id, quantity, unit_price)
  select new_order, t, p.id, 1 + floor(random() * 4)::int, p.unit_price
  from dash_demo.products p
  where p.tenant_id = t
  order by random()
  limit 1 + floor(random() * 2)::int;

  if new_order % 10 = 0 then
    insert into dash_demo.returns (tenant_id, order_item_id, quantity, refunded_amount, returned_at)
    select t, i.id, i.quantity, i.quantity * i.unit_price, now()
    from dash_demo.order_items i
    join dash_demo.orders o on o.id = i.order_id
    where i.tenant_id = t
      and o.ordered_at > now() - interval '30 days'
      and not exists (select 1 from dash_demo.returns r where r.order_item_id = i.id)
    order by random()
    limit 1;
  end if;
end
$$;
