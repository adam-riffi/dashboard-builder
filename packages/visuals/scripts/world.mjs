// Writes src/world.ts, the map visual's geometry (ADR 0014): Natural Earth's 110 m countries
// (public domain) as world-atlas's TopoJSON (ISC), each country named by its ISO 3166-1 alpha-2
// code so query results match it. Run with `pnpm --filter @adam-riffi/dash-visuals world`.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import countries from "i18n-iso-countries";

const require = createRequire(import.meta.url);
const topology = JSON.parse(
  readFileSync(require.resolve("world-atlas/countries-110m.json"), "utf8"),
);
for (const geometry of topology.objects.countries.geometries) {
  // A few territories have no numeric code (Kosovo, Northern Cyprus): they keep their name.
  const code = geometry.id ? countries.numericToAlpha2(geometry.id) : undefined;
  geometry.properties = { name: code ?? geometry.properties.name };
  delete geometry.id;
}
delete topology.objects.land;
// Antarctica has no customers and would take a fifth of the map's height.
topology.objects.countries.geometries = topology.objects.countries.geometries.filter(
  (g) => g.properties.name !== "AQ",
);

const out = new URL("../src/world.ts", import.meta.url);
writeFileSync(
  out,
  [
    "// Generated by scripts/world.mjs: do not edit. Natural Earth 110 m countries (public domain),",
    "// from world-atlas (ISC), named by ISO 3166-1 alpha-2 code.",
    `export const world: unknown = JSON.parse(${JSON.stringify(JSON.stringify(topology))});`,
    "",
  ].join("\n"),
);
console.log(`src/world.ts: ${topology.objects.countries.geometries.length} countries`);
